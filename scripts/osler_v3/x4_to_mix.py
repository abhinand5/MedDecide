"""osler_v3 X4 to mix rows (ADVISORY X4, X6, X8): the chart items of osler_v2's generator as mix rows.

The chart rows (osler_v2 W3b format: template in 'generator', family, role, pair_id, patient_id) become make_row rows, so the fast
dev v3 pool (X6), the new test pool (X6) and block B3 (X8) read them like every other source. Templates the X4 check blocked
(D44(b); outputs/osler_v3/X4/checks.json) are excluded from every split. Every exclusion is counted (no silent drops).

Output: data/train/osler_v3/x4_train.jsonl (B3), data/bench/osler_v3/x4_dev.jsonl (fast dev v3), data/bench/osler_v3/x4_test.jsonl
(new test pool), and outputs/osler_v3/X4/to_mix.json (counts per template and split).

Usage:  source scripts/pod_env.sh && uv run --frozen python scripts/osler_v3/x4_to_mix.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

from meddecide.mix.rows import make_row
from meddecide.utils.io import read_json, write_json, write_jsonl
from meddecide.utils.provenance import git_commit, utcnow

REPO = Path(__file__).resolve().parents[2]
GEN = REPO / "data" / "gen" / "osler_v3" / "charts"
CHECKS = REPO / "outputs" / "osler_v3" / "X4" / "checks.json"
OUT = REPO / "outputs" / "osler_v3" / "X4" / "to_mix.json"
DEST = {
    "train": REPO / "data" / "train" / "osler_v3" / "x4_train.jsonl",
    "dev": REPO / "data" / "bench" / "osler_v3" / "x4_dev.jsonl",
    "test": REPO / "data" / "bench" / "osler_v3" / "x4_test.jsonl",
}
SOURCE = "synthea_chart"
TIER = "osler_v3_chart"
LICENCE = "MIT (Synthea-derived patient data; the chart text is generated by code)"  # richardyoung/synthea-575k-patients, MIT


def convert(row: dict[str, Any]) -> dict[str, Any]:
    meta = {"family": row["family"], "role": row["role"], "pair_id": row["pair_id"], "patient_id": row["patient_id"],
            "generator": row["generator"], **dict(row.get("meta") or {})}
    return make_row(source=SOURCE, template_id=row["generator"], skill=row["family"], qtype=row["qtype"], state=row["state"],
                    question=row["question"], options=[(o["key"], o["label"]) for o in row["options"]], gold=row["gold"],
                    record_id=f"{row['pair_id']}|{row['role']}", record_url="", licence=LICENCE, record_date="",
                    split=row["split"], tier=TIER, meta=meta)


def main() -> int:
    checks = read_json(CHECKS)
    blocked = sorted(t for t, info in checks["templates"].items() if info.get("blocked"))
    report: dict[str, Any] = {"built_utc": utcnow(), "git_commit": git_commit(REPO), "checks": str(CHECKS.relative_to(REPO)),
                              "blocked_templates": blocked, "splits": {}}
    for split, path in DEST.items():
        rows = [json.loads(line) for line in (GEN / f"{split}.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
        if any(r["split"] != split for r in rows):
            raise SystemExit(f"{split}: a chart row carries another split (the file and the row disagree)")
        kept = [r for r in rows if r["generator"] not in blocked]
        out = [convert(r) for r in kept]
        write_jsonl(path, out)
        report["splits"][split] = {"read": len(rows), "excluded_blocked_template": len(rows) - len(kept), "written": len(out),
                                   "by_template": dict(Counter(r["generator"] for r in kept)),
                                   "file": str(path.relative_to(REPO))}
        print(f"{split}: read {len(rows)}, excluded (blocked) {len(rows) - len(kept)}, written {len(out)}", flush=True)
    write_json(OUT, report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
