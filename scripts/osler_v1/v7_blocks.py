"""V7: the cumulative training blocks of osler_v1 (ADVISORY V7; D17, D20, D27, D32).

  B0  mix v2 (osler_v0, 573,611 train rows) + the permissive general replay (V3, 80,303 rows)
  B1  B0 + the MR generators (V1, train) + the Synthea items (V5a, train); the tabular page-category items (V1 and Synthea)
      together are capped at 2 % of the block's rows (ADVISORY V7); the cap is sampled deterministically and counted
  B2  B1 + the teacher prose (V4, train): indicator prose and the narrative pages (the ICD prose is BLOCKED, STATE §5)
  B3  B2 + the real clinical text (V5b, train: MTSamples, CodiEsp corpus train, PMC-Patients train pairs)
  B4  not built: MIMIC is not present (V5c)

The V4 build appends verified teacher items as they are made, so B2 and B3 are built only once the teacher prose is final
(V4 done, or stopped by the budget with the decision recorded in STATE): pass --teacher-final.

Each row is written in the mix v2 schema (the trainer reads it with ``meddecide.train.mix_items``). Rules enforced here: no
template above 8 % of a block (D17); held-out rows excluded everywhere; a row whose bare source record id is held by a
protected training set (the v0.2 dev or test set, the panel, the robustness pack) is dropped and counted (V7-D4); and the
leakage check of each block against the v0.2 test, the external panel and the MR test suite (text keys and bare ids, after
the drop), with the dataset-qualified record identity (O4's rule) counted as well.

Outputs (gitignored): data/train/osler_v1/block_B<k>.jsonl and outputs/osler_v1/V7/blocks.json (merged across runs).

Usage:
    source scripts/pod_env.sh && uv run --frozen python scripts/osler_v1/v7_blocks.py --blocks B0 B1
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import random
from collections import Counter
from pathlib import Path
from typing import Any

from meddecide.mix.leakage import bare_collisions, leak_counts, qualified_collisions, row_text_key
from meddecide.mr.generators import is_held_out
from meddecide.utils.hashing import file_sha256
from meddecide.utils.io import read_json, write_json
from meddecide.utils.provenance import git_commit, utcnow

REPO = Path(__file__).resolve().parents[2]
OUT_DATA = REPO / "data" / "train" / "osler_v1"
OUT_MANIFEST = REPO / "outputs" / "osler_v1" / "V7" / "blocks.json"
MIX_V2 = REPO / "data" / "train" / "osler_v0" / "train.jsonl"
REPLAY = OUT_DATA / "replay_v1_train.jsonl"
V1_TRAIN = REPO / "data" / "gen" / "osler_v1" / "train.jsonl"
SYN_TRAIN = REPO / "data" / "gen" / "osler_v1_synthea" / "train.jsonl"
REALTEXT = REPO / "data" / "gen" / "osler_v1" / "realtext"
TEACHER = REPO / "data" / "gen" / "osler_v1" / "teacher"
TEST_SETS = {
    "mr_test": REPO / "data" / "bench" / "osler_mr_v0" / "mr_test.jsonl",
    "mr_heldout": REPO / "data" / "bench" / "osler_mr_v0" / "mr_heldout.jsonl",
}
TABULAR_PAGE = ("mr_page_category_tabular_v1", "synthea_page_category_v1")
GENERAL_REPLAY = frozenset({"commonsenseqa", "qasc", "hellaswag", "winogrande"})
PAGE_CAP = 0.02
TEMPLATE_CAP = 0.08
TEACHER_BLOCKS = ("B2", "B3")
SOURCES = {
    "mr_v1": {"url": "https://github.com/abhinand5/MedDecide", "licence": "generated by code (this repository)"},
    "mr_synthea": {"url": "https://huggingface.co/datasets/richardyoung/synthea-575k-patients",
                   "licence": "MIT (Synthea)"},
    "mr_teacher": {"url": "https://github.com/abhinand5/MedDecide",
                   "licence": "generated: code facts and teacher prose verified by re-extraction (D27)"},
    "mr_mtsamples": {"url": "https://huggingface.co/datasets/harishnair04/mtsamples",
                     "licence": "uncertain; accepted by the operator (D32)"},
    "mr_codiesp": {"url": "https://huggingface.co/datasets/Biomedical-TeMU/CodiEsp_corpus", "licence": "CC BY 4.0"},
    "mr_pmc": {"url": "https://huggingface.co/datasets/zhengyun21/PMC-Patients",
               "licence": "CC BY-NC-SA 4.0 (comm subset)"},
}
RECORD_DATE = "2026-10-13"


def mix_row_from_item(raw: dict[str, Any], *, source: str, skill: str) -> dict[str, Any]:
    """A generated or real-text item row as a mix v2 training row."""
    lic = SOURCES[source]
    return {
        "item_id": raw["item_id"], "tier": "training", "source": source,
        "source_record_id": raw.get("pair_id") or raw["item_id"], "source_url": lic["url"],
        "source_license": lic["licence"], "record_date": RECORD_DATE, "split": raw["split"],
        "template_id": raw["generator"], "skill": skill, "qtype": raw["qtype"], "state": raw["state"],
        "question": raw["question"], "options": [{"key": o["key"], "label": o["label"]} for o in raw["options"]],
        "gold": raw["gold"],
    }


def read_jsonl(path: Path):
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                yield json.loads(line)


def load_protected() -> tuple[dict[str, set[str]], dict[str, set[str]], dict[str, set[str]]]:
    """The training protected sets of O4 (osler_v0): text keys, bare record ids and dataset-qualified record ids."""
    spec = importlib.util.spec_from_file_location("o4_build_mix", REPO / "scripts" / "osler" / "o4_build_mix.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    prot = module.protected_sets()["train"]
    text = {f"v0_{k}": v for k, v in prot["text"].items()}
    bare = {f"v0_{k}": v for k, v in prot["bare"].items()}
    qualified = {f"v0_{k}": v for k, v in prot["qualified"].items()}
    return text, bare, qualified


def mr_test_keys(path: Path) -> set[str]:
    return {row_text_key(r) for r in read_jsonl(path)}


def build_block(name: str, parts: list[tuple[str, list[dict[str, Any]]]],
                bare: dict[str, set[str]]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Concatenate the parts, drop the bare-id collisions (V7-D4), cap the tabular page-category rows (B1 onwards) and check
    the template cap. The cap is sampled with a fixed seed, so every build of a block is the same."""
    counts: Counter[str] = Counter()
    rows: list[dict[str, Any]] = []
    for _, part in parts:
        for r in part:
            hit = bare_collisions(r, bare)
            if hit:
                counts[f"row dropped: bare record id held by {'+'.join(hit)} (V7-D4)"] += 1
                continue
            rows.append(r)
    rng = random.Random(0)
    if name in ("B1", "B2", "B3"):
        tabular = [r for r in rows if r["template_id"] in TABULAR_PAGE]
        others = [r for r in rows if r["template_id"] not in TABULAR_PAGE]
        # the cap is over the block's final size, so solve for the largest tabular count that keeps it at most PAGE_CAP
        allowed = int(PAGE_CAP * len(others) / (1 - PAGE_CAP))
        if len(tabular) > allowed:
            keep = set(rng.sample(range(len(tabular)), allowed))
            counts["tabular page-category rows dropped by the 2 % cap"] = len(tabular) - allowed
            tabular = [r for i, r in enumerate(tabular) if i in keep]
        rows = others + tabular
    by_template = Counter(r["template_id"] for r in rows)
    biggest = max(by_template.values()) / len(rows)
    info = {"rows": len(rows), "by_source": dict(Counter(r["source"] for r in rows)),
            "by_template": dict(sorted(by_template.items())), "largest_template_share": round(biggest, 4),
            "template_cap_ok": biggest <= TEMPLATE_CAP,
            "tabular_page_share": round(sum(by_template[t] for t in TABULAR_PAGE) / len(rows), 4),
            "replay_share": round(sum(1 for r in rows if r["source"] in GENERAL_REPLAY) / len(rows), 4),
            "dropped": dict(counts), "splits": dict(Counter(r["split"] for r in rows))}
    return rows, info


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--blocks", nargs="+", default=["B0", "B1"], choices=["B0", "B1", "B2", "B3"])
    parser.add_argument("--teacher-final", action="store_true",
                        help="the teacher prose is final (V4 done, or stopped by the budget with the decision recorded)")
    args = parser.parse_args()
    if set(args.blocks) & set(TEACHER_BLOCKS) and not args.teacher_final:
        parser.error("B2 and B3 read the teacher prose: build them once V4 is final, with --teacher-final")
    OUT_DATA.mkdir(parents=True, exist_ok=True)
    protected_text, protected_bare, protected_qualified = load_protected()
    tests = {"mr_test": mr_test_keys(TEST_SETS["mr_test"]), "mr_heldout": mr_test_keys(TEST_SETS["mr_heldout"])}

    # the parts, each already in the mix v2 schema; held-out rows and held-out families are excluded everywhere
    def generated(path: Path, source: str, skill: str) -> list[dict[str, Any]]:
        out = []
        for r in read_jsonl(path):
            if r["split"] != "train" or is_held_out(r["meta"]) or r.get("held_out"):
                continue
            out.append(mix_row_from_item(r, source=source, skill=skill))
        return out

    mix_v2 = [json.loads(line) for line in MIX_V2.open(encoding="utf-8")]
    b0_parts = [("mix_v2", mix_v2), ("replay", [json.loads(line) for line in REPLAY.open(encoding="utf-8")])]
    b1_extra = [("mr_v1", generated(V1_TRAIN, "mr_v1", "mr_audit")),
                ("mr_synthea", generated(SYN_TRAIN, "mr_synthea", "mr_audit"))]
    b2_extra = [("teacher", [mix_row_from_item(r, source="mr_teacher", skill="mr_audit")
                             for r in read_jsonl(TEACHER / "indicator.jsonl") if r["split"] == "train"]
                 if (TEACHER / "indicator.jsonl").exists() else []),
                ("teacher_narrative", [mix_row_from_item(r, source="mr_teacher", skill="mr_narrative")
                                       for r in read_jsonl(TEACHER / "narrative.jsonl") if r["split"] == "train"]
                 if (TEACHER / "narrative.jsonl").exists() else [])]
    b3_extra = [("mtsamples", generated(REALTEXT / "mtsamples_page_category_v1.jsonl", "mr_mtsamples", "mr_audit")),
                ("codiesp", generated(REALTEXT / "codiesp_icd_support_v1.jsonl", "mr_codiesp", "mr_audit")),
                ("pmc", generated(REALTEXT / "pmc_similar_patient_v1.jsonl", "mr_pmc", "mr_clinical"))]
    recipes = {"B0": b0_parts, "B1": b0_parts + b1_extra, "B2": b0_parts + b1_extra + b2_extra,
               "B3": b0_parts + b1_extra + b2_extra + b3_extra}

    manifest: dict[str, Any] = (read_json(OUT_MANIFEST) if OUT_MANIFEST.exists() else {"blocks": {}, "runs": []})
    for name in args.blocks:
        rows, info = build_block(name, recipes[name], protected_bare)
        # the leakage check of the block: text keys and bare ids (zero after the drop) against every test-side set, and the
        # dataset-qualified record identity (O4's rule) against the v0.2 and panel sets
        info["leakage_hits"] = {k: v for k, v in leak_counts(rows, {**protected_text, **tests}, protected_bare).items()
                                if v}
        qualified: Counter[str] = Counter()
        for r in rows:
            for hit in qualified_collisions(r, protected_qualified):
                qualified[f"qualified:{hit}"] += 1
        info["qualified_record_hits"] = dict(qualified)
        info["leakage_clean"] = not info["leakage_hits"] and not info["qualified_record_hits"]
        info["teacher_final_flag"] = args.teacher_final if name in TEACHER_BLOCKS else None
        out = OUT_DATA / f"block_{name}.jsonl"
        with out.open("w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")
        info["file"] = str(out.relative_to(REPO))
        info["sha256_file"] = file_sha256(out)
        info["written_utc"] = utcnow()
        manifest["blocks"][name] = info
        print(name, info["rows"], "replay", info["replay_share"], "largest", info["largest_template_share"],
              "tabular", info["tabular_page_share"], "leak", info["leakage_clean"], "hits", info["leakage_hits"],
              "qualified", info["qualified_record_hits"], flush=True)
    manifest["written_utc"] = utcnow()
    manifest["git_commit"] = git_commit(REPO)
    manifest.setdefault("runs", []).append({"utc": utcnow(), "blocks": args.blocks, "teacher_final": args.teacher_final})
    write_json(OUT_MANIFEST, manifest)


if __name__ == "__main__":
    main()
