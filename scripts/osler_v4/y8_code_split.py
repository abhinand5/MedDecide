"""Y8 additional analysis (dev only; the operator's steer of 2026-10-24): CG v2 by option-code type, and per template, for four models.

It reads four CG v2 prediction files and the CG v2 bench file, and nothing else: zero-shot pplx-decider-flash-v1.2 (Y4), osler_v2
(Y4), A0 (the Stage A control, Y6) and the Y8 final model. It computes the DDXPlus accuracy by gold code (a single-letter gold,
index below 26, or a two-letter gold, index 26 and up) with the mean probability mass on two-letter codes, and the CG v2 accuracy
per template, with the D12 readout gate applied to each (model, template) cell. The flash file carries the gold key only, so its
gold index comes from the key. Every file's keys are checked against the A0 file, and every item's identity against the bench
file (split dev, no held-out item). No external-panel item and no test item is read.

Writes outputs/osler_v4/Y8/code_split.json (counts and figures; no item text). With --write-md it also writes the additional section
of loops/osler_v4/results.md, and only after the Y8 final run has finished (final_result.json exists). Exits 1 when any validation
count is not zero.

Usage (CPU): CUDA_VISIBLE_DEVICES= uv run --frozen python scripts/osler_v4/y8_code_split.py [--write-md] [--out PATH]
"""

from __future__ import annotations

import argparse
import hashlib
import math
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from meddecide.eval.code_split import (
    option_index,
    place_section,
    render_code_section,
    split_by_gold_code,
)
from meddecide.eval.readout_gate import gate_by_template
from meddecide.train.mix_items import mix_row_to_item
from meddecide.utils.io import iter_jsonl, write_json
from meddecide.utils.provenance import utcnow

REPO = Path(__file__).resolve().parents[2]
Y4 = REPO / "outputs" / "osler_v4" / "Y4" / "baselines"
Y6 = REPO / "outputs" / "osler_v4" / "Y6"
Y8 = REPO / "outputs" / "osler_v4" / "Y8"
CG_FILE = REPO / "data" / "bench" / "osler_v4" / "cg_v2.jsonl"
RESULTS_MD = REPO / "loops" / "osler_v4" / "results.md"
DDX_TEMPLATE = "cg_v2_ddxplus_validate_v1"
DDX_OPTIONS = 49
REFERENCE = "a0"  # the trainer-based file every other run is checked against (the same CG v2 items)
RUNS = {
    "zero_shot_pplx_flash": ("zero-shot pplx-decider-flash-v1.2", Y4 / "cg_v2_flash" / "predictions.jsonl"),
    "osler_v2": ("osler_v2 Osler-4B (Y4)", Y4 / "cg_v2_osler_v2" / "predictions.jsonl"),
    "a0": ("A0 control (Stage A, 13,992 steps)", Y6 / "A0" / "cg_v2_predictions.jsonl"),
    "y8_final": ("Y8 final (63,304 steps)", Y8 / "cg_v2_predictions.jsonl"),
}
TRAINER_BASED = ("osler_v2", "a0", "y8_final")  # these score every CG v2 item; the zero-shot runner skips some
HEADER = "# osler_v4 — results\n\nRows are generated by scripts, and each section names its source. Additional rows carry no verdict.\n"


@dataclass(frozen=True)
class Scored:
    """One scored item: its template, gold key and index, predicted key, correct flag and probability vector."""

    template: str
    gold_key: str
    gold_index: int
    predicted_key: str
    correct: bool
    probs: tuple[float, ...]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def load_run(path: Path, checks: Counter[str]) -> tuple[dict[str, Scored], int, int]:
    """One run's scored items keyed by item id, the rows read and the rows not scored. Each failed check adds one to ``checks``."""
    items: dict[str, Scored] = {}
    read = skipped = 0
    for row in iter_jsonl(path):
        read += 1
        if row.get("status", "scored") != "scored":
            skipped += 1
            continue
        item_id = str(row["item_id"])
        if item_id in items:
            checks["duplicate item ids"] += 1
            continue
        probs = tuple(float(p) for p in row["probs"])
        gold_key, predicted_key = str(row["gold_key"]), str(row["predicted_key"])
        gold, predicted = option_index(gold_key), option_index(predicted_key)
        if "gold_index" in row and int(row["gold_index"]) != gold:
            checks["gold index differs from the gold key"] += 1
        if "predicted_index" in row and int(row["predicted_index"]) != predicted:
            checks["predicted index differs from the predicted key"] += 1
        if "n_options" in row and int(row["n_options"]) != len(probs):
            checks["n_options differs from the probability vector"] += 1
        if not gold < len(probs):
            checks["gold index outside the probability vector"] += 1
        if not all(math.isfinite(p) and p >= 0 for p in probs):
            checks["probabilities not finite or negative"] += 1
        if abs(sum(probs) - 1.0) > 1e-3:
            checks["probability vectors not summing to one"] += 1
        if predicted != max(range(len(probs)), key=probs.__getitem__):
            checks["predicted key is not the argmax"] += 1
        if bool(row["correct"]) != (predicted_key == gold_key):
            checks["correct flag differs from the keys"] += 1
        items[item_id] = Scored(template=str(row["template_id"]), gold_key=gold_key, gold_index=gold, predicted_key=predicted_key,
                                correct=bool(row["correct"]), probs=probs)
    return items, read, skipped


def bench_identities(checks: Counter[str]) -> dict[str, bool]:
    """Every CG v2 bench item by its recomputed item id: True when its option labels repeat. Also checks the split and held-out flags."""
    repeated: dict[str, bool] = {}
    for row in iter_jsonl(CG_FILE):
        item = mix_row_to_item(row)
        if row.get("split") != "dev":
            checks["CG v2 bench items outside the dev split"] += 1
        if row.get("held_out") is True:
            checks["CG v2 bench held-out items"] += 1
        labels = [option.label for option in item.options]
        repeated[item.item_id] = len(set(labels)) < len(labels)
    return repeated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write-md", action="store_true", help="also write the additional section of results.md (after the Y8 final run)")
    parser.add_argument("--out", type=Path, default=Y8 / "code_split.json", help="the JSON to write (default outputs/osler_v4/Y8/code_split.json)")
    args = parser.parse_args()
    if args.write_md and args.out != Y8 / "code_split.json":
        raise SystemExit("--write-md refused: results.md is written only from the default JSON path")

    validation: dict[str, Counter[str]] = {}
    inputs: dict[str, Any] = {}
    runs: dict[str, dict[str, Scored]] = {}
    for key, (label, path) in RUNS.items():
        if not path.exists():
            continue
        checks: Counter[str] = Counter()
        items, read, skipped = load_run(path, checks)
        validation[key] = checks
        runs[key] = items
        inputs[key] = {"label": label, "file": str(path.relative_to(REPO)), "sha256": sha256(path), "rows_read": read,
                       "rows_not_scored": skipped, "items": len(items)}
    if REFERENCE not in runs:
        raise SystemExit(f"the reference run {REFERENCE} has no predictions file")

    bench_checks: Counter[str] = Counter()
    repeated = bench_identities(bench_checks)
    validation["cg_v2_bench"] = bench_checks
    ref = runs[REFERENCE]
    matching: Counter[str] = Counter()
    matching["reference items not in the CG v2 bench file"] += len(ref.keys() - repeated.keys())
    unscored: dict[str, Any] = {"run": None, "items": 0, "repeated_label_items": 0, "by_template": {}}
    for key, items in runs.items():
        if key == REFERENCE:
            continue
        matching[f"{key}: items not in the reference"] += len(items.keys() - ref.keys())
        for item_id in items.keys() & ref.keys():
            if items[item_id].gold_index != ref[item_id].gold_index:
                matching[f"{key}: gold index differs from the reference"] += 1
        missing = ref.keys() - items.keys()
        if key in TRAINER_BASED:
            matching[f"{key}: reference items missing"] += len(missing)
        elif missing:
            unscored = {"run": key, "items": len(missing), "repeated_label_items": sum(repeated.get(i, False) for i in missing),
                        "by_template": dict(sorted(Counter(ref[i].template for i in missing).items()))}
    validation["matching"] = matching

    gates = {key: gate_by_template({"template_id": s.template, "gold_key": s.gold_key, "predicted_key": s.predicted_key,
                                    "correct": s.correct, "probs": s.probs} for s in items.values())
             for key, items in runs.items()}
    templates = []
    for template in sorted({s.template for s in ref.values()}):
        row: dict[str, Any] = {"template": template, "items": {}, "accuracy": {}, "status": {}}
        for key, items in runs.items():
            cell = [s for s in items.values() if s.template == template]
            row["items"][key] = len(cell)
            row["accuracy"][key] = sum(s.correct for s in cell) / len(cell) if cell else None
            row["status"][key] = gates[key][template].status if cell else "NOT RUN"
        templates.append(row)

    ddx: dict[str, Any] = {}
    ddx_checks: Counter[str] = Counter()
    for key, items in runs.items():
        cell = [s for s in items.values() if s.template == DDX_TEMPLATE]
        ddx_checks["DDXPlus items without the 49 options"] += sum(len(s.probs) != DDX_OPTIONS for s in cell)
        split = split_by_gold_code([(s.gold_index, s.correct, s.probs) for s in cell]) if cell else None
        ddx[key] = {"status": gates[key][DDX_TEMPLATE].status if cell else "NOT RUN", "split": split}
    validation["ddxplus"] = ddx_checks
    ref_split = ddx[REFERENCE]["split"]
    if ref_split is None:
        raise SystemExit("the reference run has no DDXPlus items")
    result: dict[str, Any] = {
        "generated_utc": utcnow(),
        "labels": {key: RUNS[key][0] for key in runs},
        "reference": REFERENCE,
        "reference_name": "A0",
        "inputs": inputs,
        "validation": {run: dict(checks) for run, checks in validation.items()},
        "unscored": unscored,
        "ddx_items": ref_split["items"],
        "ddx_gold_two_letter_share": ref_split["two_letter_gold"]["items"] / ref_split["items"],
        "ddxplus": ddx,
        "templates": templates,
    }
    failures = sum(sum(checks.values()) for checks in validation.values())
    write_json(args.out, result)
    print(f"Y8 code split: {len(runs)} runs; {ref_split['items']} DDXPlus items; validation failures {failures}; wrote {args.out}",
          flush=True)
    if failures:
        raise SystemExit(1)
    if args.write_md:
        if not (Y8 / "final_result.json").exists():
            raise SystemExit("--write-md refused: the Y8 final run has not finished (no final_result.json)")
        if set(runs) != set(RUNS):
            raise SystemExit("--write-md refused: a run's predictions are missing")
        current = RESULTS_MD.read_text(encoding="utf-8") if RESULTS_MD.exists() else HEADER
        RESULTS_MD.write_text(place_section(current, render_code_section(result)), encoding="utf-8")
        print(f"wrote the additional section to {RESULTS_MD}", flush=True)


if __name__ == "__main__":
    main()
