"""Teacher prose from code-built facts, verified by re-extraction (D27: code computes the label, the teacher writes the
text).

One request = one set of structured facts (a diagnosis, or the observations of a chunk) plus a page class and a style.
The teacher writes the page; a second call extracts the facts back from the text as JSON; the item is kept only when the
extracted facts equal the source facts on every field the label depends on. The label is always computed by code from
the source facts, never read from the teacher.

Hosted teachers (D28) only ever receive facts generated by code. ``ProseRequest.source`` records where the facts came
from; a request whose source is MIMIC (or any credentialed source) is refused unless the client is marked local, so
MIMIC text and values cannot reach a hosted API by mistake.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from dataclasses import asdict, dataclass, field
from typing import Any, Literal, Protocol

from meddecide.mr import icd
from meddecide.mr.criteria import ChunkFacts

CREDENTIALED_SOURCES = ("mimic", "physionet", "mdace")


class ChatClient(Protocol):
    """Anything with a chat-completions call that returns the assistant text."""

    local: bool

    def chat(self, messages: list[dict[str, str]], *, temperature: float, max_tokens: int) -> str: ...


@dataclass(frozen=True)
class ProseRequest:
    kind: Literal["diagnosis", "chunk", "page"]
    page_class: str                    # one of meddecide.mr.pages.PAGE_KEYS
    facts: dict[str, Any]              # diagnosis_facts(...) or chunk_facts(...)
    setting: str = "inpatient"
    style: dict[str, str] = field(default_factory=dict)   # e.g. {"length": "short", "voice": "terse resident"}
    source: str = "generated"          # where the facts came from


@dataclass(frozen=True)
class ProseResult:
    ok: bool
    text: str | None
    reasons: tuple[str, ...]
    extracted: dict[str, Any] | None


def diagnosis_facts(dx: icd.Diagnosis) -> dict[str, Any]:
    fam = icd.FAMILY_BY_KEY[dx.family]
    return {"condition": fam.condition, "family": dx.family, "attributes": dict(dx.attributes),
            "certainty": dx.certainty, "subject": dx.subject, "status": dx.status}


def page_facts(page_facts: dict[str, Any]) -> dict[str, Any]:
    """Facts for a whole narrative page (``kind="page"``), e.g. ``synthea.narrative_facts``: the label is the page class
    the code asked for; verification checks the teacher wrote that kind of page and kept the listed conditions."""
    return dict(page_facts)


def chunk_facts(facts: ChunkFacts) -> dict[str, Any]:
    return {"observations": [asdict(o) for o in facts.observations], "medications": [asdict(m) for m in facts.meds]}


STYLE_DEFAULTS = {"length": "one page", "voice": "a hospital clinician"}


def write_messages(req: ProseRequest) -> list[dict[str, str]]:
    style = {**STYLE_DEFAULTS, **req.style}
    rules = [
        f"Write one {req.page_class.replace('_', ' ')} page of an {req.setting} medical record, as {style['voice']} "
        f"would write it, about {style['length']} long.",
        "Use realistic clinical language, abbreviations and section headings. Add unrelated but plausible clinical detail "
        "(other problems, plans, exam findings) so the page reads like a real record.",
        "The FACTS below must all be stated exactly as given: same values, units, times relative to admission, certainty "
        "words, who has the condition, and whether it is current or past. Do not add any other diagnosis or measurement of "
        "the same condition or quantity, and do not contradict a fact.",
        "Do not state or hint at any billing code, and do not explain whether criteria are met.",
        "Use only invented names, dates and identifiers.",
        "Output only the page text.",
    ]
    return [
        {"role": "system", "content": "You write synthetic medical-record pages for training data. Follow the rules exactly."},
        {"role": "user", "content": "\n".join(f"- {r}" for r in rules) + "\n\nFACTS:\n" + json.dumps(req.facts, indent=2)},
    ]


def extract_messages(req: ProseRequest, text: str) -> list[dict[str, str]]:
    if req.kind == "page":
        from meddecide.mr.pages import PAGE_KEYS

        schema = {"page_type": list(PAGE_KEYS), "conditions_mentioned": ["string"]}
        ask = ("Classify the page type, and list every condition or diagnosis the page mentions as the patient's.")
        return [
            {"role": "system", "content": "You extract facts from medical-record text into JSON. Output only JSON."},
            {"role": "user", "content": f"{ask}\nSchema: {json.dumps(schema)}\n\nPAGE:\n{text}"},
        ]
    if req.kind == "diagnosis":
        schema = {"condition": "string", "attributes": {k: list(v) for k, v in
                                                         icd.FAMILY_BY_KEY[req.facts["family"]].attributes.items()},
                  "certainty": ["confirmed", "probable", "suspected", "ruled_out"], "subject": ["patient", "family"],
                  "status": ["current", "history"]}
        ask = (f"Read the page and report how it documents {req.facts['condition']}. Use exactly these fields and allowed "
               f"values; use \"unspecified\" for an attribute the page does not state.")
    else:
        schema = {"observations": [{"name": "string", "value": "number (canonical unit)", "encounter": ["current", "prior"],
                                    "baseline": "boolean", "on_room_air": "boolean"}],
                  "medications": [{"drug": "string", "status": ["given", "held", "refused", "not_given"],
                                   "encounter": ["current", "prior"]}]}
        ask = ("List every measurement and medication administration the page states for these quantities: "
               + ", ".join(sorted({o["name"] for o in req.facts["observations"]} |
                                  {m["drug"] for m in req.facts["medications"]})) + ".")
    return [
        {"role": "system", "content": "You extract facts from medical-record text into JSON. Output only JSON."},
        {"role": "user", "content": f"{ask}\nSchema: {json.dumps(schema)}\n\nPAGE:\n{text}"},
    ]


def _json(text: str) -> dict[str, Any] | None:
    m = re.search(r"\{.*\}", text, flags=re.S)
    if not m:
        return None
    try:
        out = json.loads(m.group(0))
    except json.JSONDecodeError:
        return None
    return out if isinstance(out, dict) else None


def verify(req: ProseRequest, extracted: Mapping[str, Any] | None, *, rel_tol: float = 0.02) -> list[str]:
    """Differences between the source facts and what the teacher's page states (empty = verified)."""
    if extracted is None:
        return ["extraction is not JSON"]
    problems: list[str] = []
    if req.kind == "page":
        if extracted.get("page_type") != req.page_class:
            problems.append(f"page_type: {extracted.get('page_type')!r} != {req.page_class!r}")
        said = " ".join(str(c).lower() for c in extracted.get("conditions_mentioned") or [])
        for cond in req.facts.get("conditions") or []:
            words = [w for w in str(cond).lower().replace(",", " ").split() if len(w) > 3][:3]
            if words and not all(w in said for w in words):
                problems.append(f"condition not reported: {cond}")
        return problems
    if req.kind == "diagnosis":
        f = req.facts
        for key in ("certainty", "subject", "status"):
            if extracted.get(key) != f[key]:
                problems.append(f"{key}: {extracted.get(key)!r} != {f[key]!r}")
        got = extracted.get("attributes") or {}
        for k, v in f["attributes"].items():
            if got.get(k) != v:
                problems.append(f"attribute {k}: {got.get(k)!r} != {v!r}")
        return problems
    want = sorted(((o["name"], o["value"], o["encounter"], o["baseline"], o["on_room_air"])
                   for o in req.facts["observations"]), key=lambda t: (t[0], t[1]))
    got_obs = []
    for o in extracted.get("observations") or []:
        try:
            got_obs.append((str(o["name"]), float(o["value"]), o.get("encounter", "current"),
                            bool(o.get("baseline", False)), bool(o.get("on_room_air", True))))
        except (KeyError, TypeError, ValueError):
            problems.append(f"malformed observation {o!r}")
    got_obs.sort(key=lambda t: (t[0], t[1]))
    if len(got_obs) != len(want):
        problems.append(f"observation count {len(got_obs)} != {len(want)}")
    for (wn, wv, we, wb, wr) in want:
        match = [g for g in got_obs if g[0] == wn and abs(g[1] - wv) <= rel_tol * max(abs(wv), 1e-9)
                 and g[2] == we and g[3] == wb and g[4] == wr]
        if not match:
            problems.append(f"missing or changed observation {wn}={wv:g} ({we}, baseline={wb}, room_air={wr})")
    want_meds = sorted((m["drug"].lower(), m["status"], m["encounter"]) for m in req.facts["medications"])
    got_meds = sorted((str(m.get("drug", "")).lower(), m.get("status"), m.get("encounter", "current"))
                      for m in extracted.get("medications") or [])
    if want_meds != got_meds:
        problems.append(f"medications {got_meds} != {want_meds}")
    return problems


def generate(client: ChatClient, req: ProseRequest, *, temperature: float = 0.9, max_tokens: int = 1800) -> ProseResult:
    """Write one page and verify it. Never raises on a teacher error; a failed page is returned with its reasons."""
    if req.source.lower().startswith(CREDENTIALED_SOURCES) and not getattr(client, "local", False):
        raise PermissionError(f"facts from {req.source!r} may only go to a local teacher (PhysioNet DUA; AGENTS.md)")
    try:
        text = client.chat(write_messages(req), temperature=temperature, max_tokens=max_tokens).strip()
    except Exception as exc:  # a teacher failure is a dropped item, recorded with its reason
        return ProseResult(False, None, (f"write failed: {type(exc).__name__}",), None)
    if not text:
        return ProseResult(False, None, ("empty page",), None)
    try:
        raw = client.chat(extract_messages(req, text), temperature=0.0, max_tokens=1200)
    except Exception as exc:
        return ProseResult(False, text, (f"extract failed: {type(exc).__name__}",), None)
    extracted = _json(raw)
    problems = verify(req, extracted)
    return ProseResult(not problems, text, tuple(problems), extracted)
