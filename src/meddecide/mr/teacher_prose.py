"""Teacher prose from code-built facts, verified by re-extraction (D27: code computes the label, the teacher writes the
text).

One request = one set of structured facts (a diagnosis, or the observations of a chunk) plus a page class and a style.
The teacher writes the page; a second call extracts the facts back from the text as JSON; the item is kept only when the
extracted facts equal the source facts on every field the label depends on. The label is always computed by code from
the source facts, never read from the teacher.

Hosted teachers (D28) only ever receive facts generated by code. ``ProseRequest.source`` records where the facts came
from; a request whose source is MIMIC (or any credentialed source) is refused unless the client is marked local, so
MIMIC text and values cannot reach a hosted API by mistake.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any, Literal, Protocol

from meddecide.mr import icd
from meddecide.mr.criteria import CANONICAL_UNITS, ChunkFacts
from meddecide.mr.pages import PAGE_KEYS, _fmt

CREDENTIALED_SOURCES = ("mimic", "physionet", "mdace")


class ChatClient(Protocol):
    """Anything with a chat-completions call that returns the assistant text."""

    local: bool

    def chat(self, messages: list[dict[str, str]], *, temperature: float, max_tokens: int) -> str: ...


@dataclass(frozen=True)
class ProseRequest:
    kind: Literal["diagnosis", "diagnoses", "chunk", "page"]
    page_class: str                    # one of meddecide.mr.pages.PAGE_KEYS
    facts: dict[str, Any]              # diagnosis_facts(...) or chunk_facts(...)
    setting: str = "inpatient"
    style: dict[str, str] = field(default_factory=dict)   # e.g. {"length": "short", "voice": "terse resident"}
    source: str = "generated"          # where the facts came from


@dataclass(frozen=True)
class ProseResult:
    ok: bool
    text: str | None
    reasons: tuple[str, ...]
    extracted: dict[str, Any] | None


def diagnosis_facts(dx: icd.Diagnosis) -> dict[str, Any]:
    fam = icd.FAMILY_BY_KEY[dx.family]
    return {"condition": fam.condition, "family": dx.family, "attributes": dict(dx.attributes),
            "certainty": dx.certainty, "subject": dx.subject, "status": dx.status}


def page_facts(page_facts: dict[str, Any]) -> dict[str, Any]:
    """Facts for a whole narrative page (``kind="page"``), e.g. ``synthea.narrative_facts``: the label is the page class
    the code asked for; verification checks the teacher wrote that kind of page and kept the listed conditions."""
    return dict(page_facts)


def chunk_facts(facts: ChunkFacts) -> dict[str, Any]:
    """Facts for a chunk, with every value rounded as a record would print it (osler_v1 V4-D8: unrounded values such as
    "lactate 2.873" leaked into teacher pages). The generators keep values away from each threshold by more than this
    rounding, so the code's label is unchanged."""
    obs = []
    for o in facts.observations:
        shown, unit = o.displayed()
        obs.append({"name": o.name, "value": float(_fmt(o.value, o.name)), "unit": CANONICAL_UNITS[o.name],
                    "display_value": _fmt(shown, o.name, unit), "display_unit": unit,
                    "hours_from_admission": round(o.time_h, 1), "encounter": o.encounter, "baseline": o.baseline,
                    "on_room_air": o.on_room_air})
    meds = [{"drug": m.drug, "dose": m.dose, "hours_from_admission": round(m.time_h, 1), "status": m.status,
             "encounter": m.encounter} for m in facts.meds]
    return {"observations": obs, "medications": meds}


STYLE_DEFAULTS = {"length": "half a page (about 250-350 words)", "voice": "a hospital clinician"}

# Prompts are laid out for the endpoint's automatic prefix cache: everything that is the same for every request of a
# kind sits in the system message (sent first, byte-identical), and only the request's own facts follow. Cached input
# is billed at about 2 % of the uncached rate on the OpenCode Go plan.
WRITE_SYSTEM = "\n".join([
    "You write synthetic medical-record pages for training data. Follow every rule exactly.",
    "- Write one page of the type and setting given in the request, in the voice and length given there.",
    "- Use realistic clinical language, abbreviations and section headings, and plausible unrelated narrative detail "
    "(history, exam findings without numbers, plans) so the page reads like a real record.",
    "- Every item in FACTS must be stated exactly as given: same values, units, times relative to admission, certainty "
    "words, who has the condition, and whether it is current or past. Give each value as display_value with display_unit. "
    "Make clear, in your own varied wording, when a value is from a prior admission, when it is the patient's usual or "
    "chronic level (baseline), and whether an oxygen saturation was on room air or on oxygen; never reuse one fixed "
    "phrase for these. State the administration status of every medication.",
    "- Do not state any vital sign, laboratory value or medication administration other than those in FACTS, and do not "
    "add any other diagnosis of the same condition.",
    "- Do not state or hint at any billing code, and do not say whether any criteria are met.",
    "- Use only invented names, dates and identifiers.",
    "- Output only the page text.",
])

OBS_NAMES = ("lactate", "map", "temperature", "heart_rate", "respiratory_rate", "wbc", "platelets", "bilirubin", "pao2",
             "spo2", "paco2", "ph", "fio2", "creatinine", "sodium")
EXTRACT_SYSTEM = {
    "page": "You extract facts from medical-record text into JSON. Output only JSON with the schema "
            '{"page_type": one of ' + json.dumps(list(PAGE_KEYS))
            + ', "conditions_mentioned": [every condition or diagnosis the page attributes to the patient]}.',
    "diagnosis": "You extract facts from medical-record text into JSON. Output only JSON with the schema "
                 '{"condition": string, "attributes": {attribute: value}, "certainty": "confirmed"|"probable"|'
                 '"suspected"|"ruled_out", "subject": "patient"|"family", "status": "current"|"history"}. '
                 "Report how the page documents the condition named in the request, using only the attribute names and "
                 'values the request lists, and "unspecified" for an attribute the page does not state.',
    "diagnoses": "You extract facts from medical-record text into JSON. Output only JSON with the schema "
                 '{"diagnoses": [{"condition": string, "attributes": {attribute: value}, "certainty": "confirmed"|'
                 '"probable"|"suspected"|"ruled_out", "subject": "patient"|"family", "status": "current"|"history"}]}. '
                 "List every diagnosis the page documents, one entry each, and no other. Use the attribute names and values "
                 'the request lists for each condition, and "unspecified" for an attribute the page does not state. '
                 'certainty: "ruled_out" when the page says the condition was excluded or ruled out; "suspected" for suspected '
                 'or possible; "probable" for probable or likely; otherwise "confirmed". subject: "family" only when the page '
                 'attributes the condition to a relative; otherwise "patient". status: "history" only when the page describes '
                 'the condition as past or resolved; a condition described as active, or as recently found, is "current".',
    "chunk": "You extract facts from medical-record text into JSON. Output only JSON with the schema "
             '{"observations": [{"name", "value", "encounter": "current"|"prior", "baseline": bool, '
             '"on_room_air": bool}], "medications": [{"drug", "status": "given"|"held"|"refused"|"not_given", '
             '"encounter": "current"|"prior"}]}. List EVERY vital sign and laboratory value on the page and EVERY '
             "medication administration. Use these names: " + ", ".join(OBS_NAMES) + " (map = mean arterial pressure; "
             'spo2 = pulse-oximetry saturation; fio2 in percent); give each value in the canonical unit (lactate mmol/L, '
             "creatinine and bilirubin mg/dL, temperature Celsius, PaO2 and PaCO2 mmHg, counts x10^9/L or x10^3/uL); "
             'any other measurement gets the name "other". on_room_air is true unless the page says oxygen was given.',
}


DIAGNOSES_RULES = "\n".join([
    "RULES FOR THIS PAGE (each diagnosis in FACTS must read exactly as its own status says):",
    "- certainty: write 'confirmed' as a plain diagnosis; 'probable' as probable or likely; 'suspected' as suspected or possible; "
    "'ruled_out' as ruled out or excluded.",
    "- subject 'family' means the condition belongs to a blood relative only: write it as a relative's condition (for example "
    "'mother had ...' or 'family history of ...'). Never write a family condition as the patient's own.",
    "- status 'history' means the condition is past and resolved: write it as 'history of ..., resolved'. Status 'current' means "
    "an active problem today: do not describe it as past, resolved or a recent episode.",
    "- do not mention any other admission, visit or episode of a listed condition; the page documents only what FACTS say.",
    "- write every name, date and identifier in full; never use bracketed placeholders.",
])


def write_messages(req: ProseRequest) -> list[dict[str, str]]:
    style = {**STYLE_DEFAULTS, **req.style}
    rules = f"{DIAGNOSES_RULES}\n\n" if req.kind == "diagnoses" else ""
    user = (f"PAGE TYPE: {req.page_class.replace('_', ' ')}\nSETTING: {req.setting}\nVOICE: {style['voice']}\n"
            f"LENGTH: {style['length']}\n" + (f"ALSO: {style['extra']}\n" if style.get("extra") else "")
            + f"\n{rules}FACTS:\n{json.dumps(req.facts, indent=1)}")
    return [{"role": "system", "content": WRITE_SYSTEM}, {"role": "user", "content": user}]


def extract_messages(req: ProseRequest, text: str) -> list[dict[str, str]]:
    if req.kind == "diagnosis":
        fam = icd.FAMILY_BY_KEY[req.facts["family"]]
        head = (f"CONDITION: {req.facts['condition']}\nATTRIBUTES: "
                f"{json.dumps({k: [*v, 'unspecified'] for k, v in fam.attributes.items()})}\n\n")
    elif req.kind == "diagnoses":
        seen: dict[str, str] = {}
        for dx in req.facts["diagnoses"]:
            fam = icd.FAMILY_BY_KEY[dx["family"]]
            seen.setdefault(fam.condition, json.dumps({k: [*v, "unspecified"] for k, v in fam.attributes.items()}))
        head = "CONDITIONS AND ATTRIBUTES:\n" + "\n".join(
            f"- {cond}: {attrs}" for cond, attrs in seen.items()) + "\n\n"
    else:
        head = ""
    return [{"role": "system", "content": EXTRACT_SYSTEM[req.kind]}, {"role": "user", "content": f"{head}PAGE:\n{text}"}]


SYNONYMS = {"mean arterial pressure": "map", "temp": "temperature", "hr": "heart_rate", "heart rate": "heart_rate",
            "rr": "respiratory_rate", "respiratory rate": "respiratory_rate", "white blood cells": "wbc",
            "leukocytes": "wbc", "plt": "platelets", "total bilirubin": "bilirubin", "sao2": "spo2",
            "oxygen saturation": "spo2", "po2": "pao2", "pco2": "paco2", "na": "sodium", "creat": "creatinine",
            "lactic acid": "lactate"}


def _obs_name(name: object) -> str:
    n = str(name).strip().lower().replace("-", "_")
    return SYNONYMS.get(n, n)


def _json(text: str) -> dict[str, Any] | None:
    m = re.search(r"\{.*\}", text, flags=re.S)
    if not m:
        return None
    try:
        out = json.loads(m.group(0))
    except json.JSONDecodeError:
        return None
    return out if isinstance(out, dict) else None


def _condition_words(text: str) -> list[str]:
    """Content words of a condition name, with the British "ae" read as "e" (hyponatraemia, hyponatremia)."""
    return [w for w in re.findall(r"[a-z]+", text.lower().replace("ae", "e")) if len(w) >= 4]


def condition_matches(family: str, reported: str) -> bool:
    """Whether a condition name in the extraction is the family's condition: every content word of the family's name is in it."""
    text = reported.lower().replace("ae", "e")
    return all(w in text for w in _condition_words(icd.FAMILY_BY_KEY[family].condition))


def _diagnosis_differences(entry: Mapping[str, Any], expected: Mapping[str, Any]) -> list[str]:
    out = []
    for key in ("certainty", "subject", "status"):
        if entry.get(key) != expected[key]:
            out.append(f"{key}: {entry.get(key)!r} != {expected[key]!r}")
    got = entry.get("attributes") or {}
    for k, v in expected["attributes"].items():
        if got.get(k) != v:
            out.append(f"attribute {k}: {got.get(k)!r} != {v!r}")
    return out


def verify(req: ProseRequest, extracted: Mapping[str, Any] | None, *, rel_tol: float = 0.02) -> list[str]:
    """Differences between the source facts and what the teacher's page states (empty = verified)."""
    if extracted is None:
        return ["extraction is not JSON"]
    problems: list[str] = []
    if req.kind == "page":
        if extracted.get("page_type") != req.page_class:
            problems.append(f"page_type: {extracted.get('page_type')!r} != {req.page_class!r}")
        said = " ".join(str(c).lower() for c in extracted.get("conditions_mentioned") or [])
        for cond in req.facts.get("conditions") or []:
            words = [w for w in str(cond).lower().replace(",", " ").split() if len(w) > 3][:3]
            if words and not all(w in said for w in words):
                problems.append(f"condition not reported: {cond}")
        return problems
    if req.kind == "diagnoses":
        found = [e for e in (extracted.get("diagnoses") or []) if isinstance(e, Mapping)]
        for expected in req.facts["diagnoses"]:
            matches = [e for e in found if condition_matches(expected["family"], str(e.get("condition", "")))]
            if not matches:
                problems.append(f"condition not reported: {icd.FAMILY_BY_KEY[expected['family']].condition}")
                continue
            problems.extend(min((_diagnosis_differences(e, expected) for e in matches), key=len))
        return problems
    if req.kind == "diagnosis":
        f = req.facts
        for key in ("certainty", "subject", "status"):
            if extracted.get(key) != f[key]:
                problems.append(f"{key}: {extracted.get(key)!r} != {f[key]!r}")
        got = extracted.get("attributes") or {}
        for k, v in f["attributes"].items():
            if got.get(k) != v:
                problems.append(f"attribute {k}: {got.get(k)!r} != {v!r}")
        return problems
    want = sorted(((o["name"], o["value"], o["encounter"], o["baseline"], o["on_room_air"])
                   for o in req.facts["observations"]), key=lambda t: (t[0], t[1]))
    got_obs = []
    for o in extracted.get("observations") or []:
        try:
            name = _obs_name(o["name"])
            if name not in OBS_NAMES:
                continue  # "other" measurements (weight, glucose, ...) do not touch any indicator
            got_obs.append((name, float(o["value"]), o.get("encounter", "current"),
                            bool(o.get("baseline", False)), bool(o.get("on_room_air", True))))
        except (KeyError, TypeError, ValueError):
            problems.append(f"malformed observation {o!r}")
    got_obs.sort(key=lambda t: (t[0], t[1]))
    if len(got_obs) != len(want):
        problems.append(f"indicator-relevant observation count {len(got_obs)} != {len(want)} (an invented value?)")
    for (wn, wv, we, wb, wr) in want:
        match = [g for g in got_obs if g[0] == wn and abs(g[1] - wv) <= rel_tol * max(abs(wv), 1e-9)
                 and g[2] == we and g[3] == wb and g[4] == wr]
        if not match:
            problems.append(f"missing or changed observation {wn}={wv:g} ({we}, baseline={wb}, room_air={wr})")
    want_meds = sorted((m["drug"].lower(), m["status"], m["encounter"]) for m in req.facts["medications"])
    got_meds = sorted((str(m.get("drug", "")).lower(), m.get("status"), m.get("encounter", "current"))
                      for m in extracted.get("medications") or [])
    if want_meds != got_meds:
        problems.append(f"medications {got_meds} != {want_meds}")
    return problems


def generate(client: ChatClient, req: ProseRequest, *, temperature: float = 0.9, max_tokens: int = 1800) -> ProseResult:
    """Write one page and verify it. Never raises on a teacher error; a failed page is returned with its reasons."""
    if req.source.lower().startswith(CREDENTIALED_SOURCES) and not getattr(client, "local", False):
        raise PermissionError(f"facts from {req.source!r} may only go to a local teacher (PhysioNet DUA; AGENTS.md)")
    try:
        text = client.chat(write_messages(req), temperature=temperature, max_tokens=max_tokens).strip()
    except Exception as exc:  # a teacher failure is a dropped item, recorded with its reason
        return ProseResult(False, None, (f"write failed: {type(exc).__name__}",), None)
    if not text:
        return ProseResult(False, None, ("empty page",), None)
    try:
        raw = client.chat(extract_messages(req, text), temperature=0.0, max_tokens=1200)
    except Exception as exc:
        return ProseResult(False, text, (f"extract failed: {type(exc).__name__}",), None)
    extracted = _json(raw)
    problems = verify(req, extracted)
    return ProseResult(not problems, text, tuple(problems), extracted)
